export interface EntryInfo {
  isDir?: boolean;
  isDrive?: boolean;
  name: string;
  type?: "pc" | "drive" | "folder" | "file";
}

export interface EntryIconOptions {
  isOpen?: boolean;
  isSelected?: boolean;
}

/**
 * Central presentational resolver returning the exact icon component for any entry.
 */
export function getEntryIcon(
  entry: EntryInfo,
  options?: EntryIconOptions
): React.ComponentType<React.SVGProps<SVGSVGElement>> {
  const normName = entry.name.trim();
  const lowerName = normName.toLowerCase();

  // 1. "This PC" / Host Root
  if (
    entry.type === "pc" ||
    lowerName === "this pc" ||
    lowerName === "this_pc" ||
    entry.name === "THIS_PC"
  ) {
    return FluentDesktop;
  }

  // 2. System Drives (e.g. C:, D:, Local Disk (C:))
  if (
    entry.type === "drive" ||
    entry.isDrive ||
    /^[a-zA-Z]:\\?$/.test(normName) ||
    lowerName.startsWith("local disk")
  ) {
    return FluentHardDrive;
  }

  // 3. Folders
  if (entry.type === "folder" || entry.isDir || entry.isDir === undefined) {
    if (options?.isOpen) {
      return FluentFolderOpen;
    }

    // Specialized well-known developer folder names
    switch (lowerName) {
      case ".git":
      case "git":
        return MatFolderGit;
      case ".github":
        return MatFolderGithub;
      case ".vscode":
        return MatFolderVscode;
      case "node_modules":
      case "packages":
      case ".pnpm":
      case "pkg":
        return MatFolderNode;
      case "src":
      case "source":
        return MatFolderSrc;
      case "dist":
      case "build":
      case "out":
      case "target":
        return MatFolderDist;
      case "docs":
      case "documentation":
      case "doc":
        return MatFolderDocs;
      case "assets":
      case "images":
      case "img":
      case "icons":
      case "media":
        return MatFolderImages;
      case "public":
      case "static":
        return MatFolderPublic;
      case "test":
      case "tests":
      case "__tests__":
      case "spec":
      case "specs":
        return MatFolderTest;
      case "config":
      case ".config":
        return MatFolderConfig;
      case "scripts":
      case "tools":
        return MatFolderScripts;
      case "components":
        return MatFolderComponents;
      case "lib":
        return MatFolderLib;
      case "hooks":
        return MatFolderHook;
      case "utils":
      case "util":
        return MatFolderUtils;
      default:
        return options?.isSelected ? FluentFolderOpen : FluentFolder;
    }
  }

  // 4. Files: by special filename or extension
  // Special filenames
  if (lowerName === "dockerfile" || lowerName.startsWith("docker-compose.")) {
    return MatDocker;
  }
  if (lowerName === "readme" || lowerName.startsWith("readme.")) {
    return MatReadme;
  }
  if (
    lowerName === ".gitignore" ||
    lowerName === ".gitattributes" ||
    lowerName === ".gitmodules"
  ) {
    return MatGitFile;
  }
  if (
    lowerName === "package.json" ||
    lowerName === "pnpm-lock.yaml" ||
    lowerName === "package-lock.json" ||
    lowerName === "yarn.lock" ||
    lowerName === "bun.lockb"
  ) {
    return MatLock;
  }
  if (
    lowerName === "tsconfig.json" ||
    lowerName.startsWith("tsconfig.") ||
    lowerName === "biome.json" ||
    lowerName === "biome.jsonc" ||
    lowerName.startsWith(".eslintrc") ||
    lowerName.startsWith("prettier.config") ||
    lowerName.startsWith(".env")
  ) {
    return MatSettings;
  }

  // Multi-dot extension check (e.g. .d.ts, .test.ts)
  if (
    lowerName.endsWith(".d.ts") ||
    lowerName.endsWith(".test.ts") ||
    lowerName.endsWith(".spec.ts")
  ) {
    return MatTypescript;
  }
  if (lowerName.endsWith(".test.js") || lowerName.endsWith(".spec.js")) {
    return MatJavascript;
  }

  // Standard extension check
  const lastDot = lowerName.lastIndexOf(".");
  if (lastDot > 0) {
    const ext = lowerName.slice(lastDot + 1);
    switch (ext) {
      // Images
      case "png":
      case "jpg":
      case "jpeg":
      case "gif":
      case "webp":
      case "svg":
      case "ico":
      case "bmp":
      case "avif":
      case "heic":
        return MatImage;
      // Video
      case "mp4":
      case "mkv":
      case "mov":
      case "avi":
      case "webm":
        return MatVideo;
      // Audio
      case "mp3":
      case "wav":
      case "flac":
      case "aac":
      case "m4a":
      case "ogg":
        return MatAudio;
      // Documents
      case "pdf":
        return MatPdf;
      case "doc":
      case "docx":
        return MatWord;
      case "xls":
      case "xlsx":
      case "csv":
        return MatTable;
      case "ppt":
      case "pptx":
        return MatPowerpoint;
      case "md":
      case "mdx":
      case "txt":
      case "rst":
        return MatMarkdown;
      // Archives
      case "zip":
      case "rar":
      case "7z":
      case "tar":
      case "gz":
      case "bz2":
        return MatZip;
      // Code
      case "ts":
      case "tsx":
        return MatTypescript;
      case "js":
      case "jsx":
      case "mjs":
      case "cjs":
        return MatJavascript;
      case "py":
        return MatPython;
      case "java":
        return MatJava;
      case "c":
      case "h":
        return MatC;
      case "cpp":
      case "cc":
      case "cxx":
      case "hpp":
        return MatCpp;
      case "cs":
        return MatCsharp;
      case "go":
        return MatGo;
      case "rs":
        return MatRust;
      case "php":
        return MatPhp;
      case "rb":
        return MatRuby;
      case "swift":
        return MatSwift;
      case "kt":
      case "kts":
        return MatKotlin;
      case "html":
      case "htm":
        return MatHtml;
      case "css":
        return MatCss;
      case "scss":
      case "sass":
      case "less":
        return MatSass;
      case "json":
      case "json5":
      case "jsonc":
        return MatJson;
      case "yaml":
      case "yml":
        return MatYaml;
      case "xml":
        return MatXml;
      case "sql":
        return MatDatabase;
      case "sh":
      case "bash":
      case "zsh":
      case "ps1":
      case "bat":
      case "cmd":
        return MatFolderScripts;
      // Executables & binaries
      case "exe":
      case "msi":
      case "dll":
        return MatExe;
      // Fonts
      case "ttf":
      case "otf":
      case "woff":
      case "woff2":
        return MatFont;
      // Databases
      case "db":
      case "sqlite":
      case "sqlite3":
      case "mdb":
        return MatDatabase;
      case "iso":
        return MatExe;
      default:
        return MatDocument;
    }
  }

  return MatDocument;
}

export function getFolderGlyph(
  name: string,
  isDir?: boolean,
  isDrive?: boolean,
  _isHidden?: boolean,
  isFileMode?: boolean,
  options?: { isOpen?: boolean; isSelected?: boolean }
) {
  return getEntryIcon(
    {
      name,
      isDir: isDir ?? true,
      isDrive,
      type: isDrive ? "drive" : isFileMode ? "file" : "folder",
    },
    options
  );
}
