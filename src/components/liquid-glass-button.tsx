function GlassFilter() {
  return (
    <svg aria-hidden="true" className="hidden size-0">
      <defs>
        <filter
          colorInterpolationFilters="sRGB"
          height="100%"
          id="container-glass"
          width="100%"
          x="0%"
          y="0%"
        >
          {/* Generate turbulent noise for distortion */}
          <feTurbulence
            baseFrequency="0.05 0.05"
            numOctaves={1}
            result="turbulence"
            seed={1}
            type="fractalNoise"
          />

          {/* Blur the turbulence pattern slightly */}
          <feGaussianBlur
            in="turbulence"
            result="blurredNoise"
            stdDeviation="2"
          />

          {/* Displace the source graphic with the noise */}
          <feDisplacementMap
            in="SourceGraphic"
            in2="blurredNoise"
            result="displaced"
            scale="70"
            xChannelSelector="R"
            yChannelSelector="B"
          />

          {/* Apply overall blur on the final result */}
          <feGaussianBlur in="displaced" result="finalBlur" stdDeviation="4" />

          {/* Output the result */}
          <feComposite in="finalBlur" in2="finalBlur" operator="over" />
        </filter>
      </defs>
    </svg>
  );
}

